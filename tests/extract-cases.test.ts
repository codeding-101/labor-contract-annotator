test('抽出案例序号、标题与三个小标题', () => {
  const { cases, issues } = extractCases(OFFICIAL_SHAPED)

  assert.equal(cases.length, 2)
  assert.equal(cases[0]?.ordinal, 1)
  assert.equal(cases[0]?.caseNo, '案例一')
  assert.match(cases[0]?.title ?? '', /^转承包建设工程/)
  assert.match(cases[1]?.title ?? '', /^关联企业混同用工/)
  assert.deepEqual(issues, [])
})

test('目录行不会被当成案例起点', () => {
  // 目录里是「案例一：…」，带冒号；正文里的标题块只有「案例一」。混淆会把目录当正文。
  const { cases } = extractCases(OFFICIAL_SHAPED)
  assert.equal(cases.length, 2)
  assert.ok(!(cases[0]?.basicFacts ?? '').startsWith('：'))
})

test('同一小标题下的多行直接拼接，不插换行', () => {
  // 原文的换行是排版折行，插换行会在句中造成假的分段
  const facts = extractCases(OFFICIAL_SHAPED).cases[0]?.basicFacts ?? ''
  assert.ok(facts.includes('刘某招用张某到工地工作。2021年10月10日'), '句子之间不应有换行')
  assert.equal(facts.includes('\n'), false)
})

