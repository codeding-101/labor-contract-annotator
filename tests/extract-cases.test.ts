  // 目录条目与正文标题形态完全一样（都是「案例一：标题」），只能靠"后面有没有小标题"区分
  const { cases, issues } = extractCases(PROVINCIAL_SHAPED)

  assert.equal(cases.length, 2)
  assert.equal(cases[0]?.title, '连续订立二次固定期限劳动合同后，用人单位不得无故拒绝与劳动者订立无固定期限劳动合同')
