import assert from 'node:assert/strict'
import { test } from 'node:test'
import { extractCases } from '../src/extract-cases.ts'

/** 按真实文档形态构造：目录 → 案例序号单独成块 → 标题 → 三个小标题。 */
const OFFICIAL_SHAPED = [
  '最高法发布劳动争议典型案例',
  '劳动争议典型案例',
  '目录',
  '案例一：转承包建设工程的个人招用的劳动者被认定工伤后，承包人负有支付工伤保险待遇的责任——某建筑公司与张某工伤保险待遇纠纷案',
  '案例二：关联企业混同用工，人民法院可根据劳动者主张并结合案情认定劳动关系——王某与某数字公司劳动合同纠纷案',
  '案例一',
  '转承包建设工程的个人招用的劳动者被认定工伤后，承包人负有支付工伤保险待遇的责任——某建筑公司与张某工伤保险待遇纠纷案',
  '【基本案情】',
  '某建筑公司将所承包工程转包给刘某。2021年8月，刘某招用张某到工地工作。',
  '2021年10月10日，张某在作业时从高处坠落受伤，诊断为腰椎骨折。',
  '【裁判结果】',
  '审理法院认为，工伤保险责任的承担并非必须以存在劳动关系作为前提条件。',
  '【典型意义】',
  '工伤保险作为社会保障体系的重要组成部分，对于保障工伤职工的权益具有重要意义。',
  '案例二',
  '关联企业混同用工，人民法院可根据劳动者主张并结合案情认定劳动关系——王某与某数字公司劳动合同纠纷案',
  '【基本案情】',
  '某数字公司系一人公司，其法定代表人、股东均为梁某。两公司系关联企业。',
  '【裁判结果】',
  '审理法院认为，关联企业混同用工的，可根据用工管理行为确认劳动关系。',
  '【典型意义】',
  '混同用工多发生于关联企业之间，本案依法纠正用人单位借混同用工规避义务的行为。',
]

test('抽出案例序号、标题与三个小标题', () => {
  const { cases, issues } = extractCases(OFFICIAL_SHAPED)

  assert.equal(cases.length, 2)
  assert.equal(cases[0]?.ordinal, 1)
  assert.equal(cases[0]?.caseNo, '案例一')
  assert.match(cases[0]?.title ?? '', /^转承包建设工程/)
  assert.match(cases[1]?.title ?? '', /^关联企业混同用工/)
  assert.deepEqual(issues, [])
})

test('目录行不会被当成案例起点', () => {
  // 目录里是「案例一：…」，带冒号；正文里的标题块只有「案例一」。混淆会把目录当正文。
  const { cases } = extractCases(OFFICIAL_SHAPED)
  assert.equal(cases.length, 2)
  assert.ok(!(cases[0]?.basicFacts ?? '').startsWith('：'))
})

test('同一小标题下的多行直接拼接，不插换行', () => {
  // 原文的换行是排版折行，插换行会在句中造成假的分段
  const facts = extractCases(OFFICIAL_SHAPED).cases[0]?.basicFacts ?? ''
  assert.ok(facts.includes('刘某招用张某到工地工作。2021年10月10日'), '句子之间不应有换行')
  assert.equal(facts.includes('\n'), false)
})

test('段落缺失或过短会被记录为问题', () => {
  const { issues } = extractCases([
    '案例一',
    '某建筑公司与张某工伤保险待遇纠纷案',
    '【基本案情】',
    '某建筑公司将所承包工程转包给刘某，刘某招用张某到工地工作。',
    '【典型意义】',
    '工伤保险作为社会保障体系的重要组成部分，对于保障工伤职工的权益具有重要意义。',
  ])
  assert.ok(issues.some((issue) => /【裁判结果】过短或缺失/.test(issue)))
})

